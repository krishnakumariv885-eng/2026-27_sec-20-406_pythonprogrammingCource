# Program to demonstrate Type Conversion

a = 10
b = 20.5
c = "100"

# Converting data types
x = float(a)
y = int(b)
z = int(c)

print("Integer to Float:", x)
print("Float to Integer:", y)
print("String to Integer:", z)

# Converting Integer to String
num = 50
s = str(num)

print("Integer to String:", s)
print("Type of s:", type(s))
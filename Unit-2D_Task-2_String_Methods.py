text = "hello python programming"

print("Uppercase:", text.upper())
print("Lowercase:", text.lower())
print("Title:", text.title())
print("Capitalize:", text.capitalize())
print("Swapcase:", text.swapcase())

print("Replace:", text.replace("python", "java"))
print("Count:", text.count("o"))
print("Find:", text.find("python"))

print("Starts with:", text.startswith("hello"))
print("Ends with:", text.endswith("programming"))

print("Is Alpha:", text.isalpha())
print("Is Digit:", text.isdigit())
print("Is Alphanumeric:", text.isalnum())